%% Superposition of 2 Beams
% Plain .m version of the core 2-beam superposition workflow from
% Testbed_Mosier_2_Beam.mlx. This script is kept workspace-friendly so it
% can be run alongside Sandbox_Methods.mlx-style experiments.

%% Setup
freq   = 3e9;
lambda = 3e8 / freq;
k0     = 2*pi / lambda;

phi_mesh = linspace(0, 2*pi, 1000 + 1);
phi_mesh(end) = [];

%% Geometry: 9-element regular ring
N  = 9;
d1 = 0.04880;
d2 = 0.04880;
[x, y] = d1d2Convert(d1, d2, N);

%% Two-beam targets and perturbation settings
phi_0_1 = deg2rad(0);
phi_0_2 = deg2rad(210);
phi_0_set = [phi_0_1 phi_0_2];

Max_iter = 200;
eps_dB   = -20;
method_name = "perturb_method_v24";
fast_peaks  = true;

null_phi_list_1 = phi_0_2;
null_phi_list_2 = phi_0_1;

%% Run the single-beam Mosier method twice
results_2A = perturb_method_v24(Max_iter, eps_dB, x, y, ...
    phi_0_1, ...
    'show_plots', false, ...
    'verbose', false, ...
    'null_phi', null_phi_list_1, ...
    'show_final_plot', true, ...
    'const_null_update', false, ...
    'fast_peaks', fast_peaks);

results_2B = perturb_method_v24(Max_iter, eps_dB, x, y, ...
    phi_0_2, ...
    'show_plots', false, ...
    'verbose', false, ...
    'null_phi', null_phi_list_2, ...
    'show_final_plot', true, ...
    'const_null_update', false, ...
    'fast_peaks', fast_peaks);

%% Reconstruct and combine the two solutions
F_reconstructed = localF2d(phi_mesh, results_2A.A_eff, x, y, [], k0);
reconstruction_error = max(abs(F_reconstructed - results_2A.final_function));

A_total_raw = results_2A.A_eff + results_2B.A_eff;
F_total_raw = localF2d(phi_mesh, A_total_raw, x, y, [], k0);

F_sum_raw = results_2A.final_function + results_2B.final_function;
raw_superposition_error = max(abs(F_total_raw - F_sum_raw));

% Match the live-script normalization used before the final plot.
F_sum_scaled = ...
    (N * results_2A.final_function / max(abs(results_2A.final_function))) + ...
    (N * results_2B.final_function / max(abs(results_2B.final_function)));

A_total_scaled = ...
    (N * results_2A.A_eff / max(abs(results_2A.final_function))) + ...
    (N * results_2B.A_eff / max(abs(results_2B.final_function)));

F_tmp = localF2d(phi_mesh, A_total_scaled, x, y, [], k0);
den = max(abs(F_tmp));
if den < 1e-12
    warning('F_tmp nearly zero; skipping normalization.');
    F_total_superposed = F_tmp;
else
    F_total_superposed = F_tmp * (max(abs(F_sum_scaled)) / den);
end

scaled_superposition_error = max(abs(F_sum_scaled - F_total_superposed));

%% Plot the combined 2-beam result
plot_label = "Final Plot: Basic (Superposition) 2-Beam";

plot_pattern_v5(phi_mesh, abs(F_total_superposed), ...
    'label', plot_label, ...
    'phi_0', phi_0_set, ...
    'show_plots', true, ...
    'cone_rad', [], ...
    'iter', max(results_2A.final_iteration, results_2B.final_iteration));

%% Collect outputs for later workspace use
superposition_results = struct( ...
    'freq', freq, ...
    'lambda', lambda, ...
    'k0', k0, ...
    'phi_mesh', phi_mesh, ...
    'x', x, ...
    'y', y, ...
    'N', N, ...
    'd1', d1, ...
    'd2', d2, ...
    'phi_0_1', phi_0_1, ...
    'phi_0_2', phi_0_2, ...
    'phi_0_set', phi_0_set, ...
    'Max_iter', Max_iter, ...
    'eps_dB', eps_dB, ...
    'method_name', method_name, ...
    'fast_peaks', fast_peaks, ...
    'results_2A', results_2A, ...
    'results_2B', results_2B, ...
    'A_total_raw', A_total_raw, ...
    'A_total_scaled', A_total_scaled, ...
    'F_total_raw', F_total_raw, ...
    'F_sum_raw', F_sum_raw, ...
    'F_sum_scaled', F_sum_scaled, ...
    'F_total_superposed', F_total_superposed, ...
    'reconstruction_error', reconstruction_error, ...
    'raw_superposition_error', raw_superposition_error, ...
    'scaled_superposition_error', scaled_superposition_error);

fprintf('reconstruction_error       = %.3e\n', reconstruction_error);
fprintf('raw_superposition_error    = %.3e\n', raw_superposition_error);
fprintf('scaled_superposition_error = %.3e\n', scaled_superposition_error);

function F = localF2d(phi_loc, A_loc, x_loc, y_loc, delta_loc, k0_loc)
%LOCALF2D Compute the 2D array factor on an azimuth mesh.
    A_loc = A_loc(:);
    x_loc = x_loc(:);
    y_loc = y_loc(:);

    if isempty(delta_loc)
        delta_loc = zeros(size(A_loc));
    else
        delta_loc = delta_loc(:);
    end

    phi_loc = phi_loc(:).';
    phase = k0_loc * (x_loc * cos(phi_loc) + y_loc * sin(phi_loc)) + delta_loc;
    F = A_loc.' * exp(1j * phase);
end
